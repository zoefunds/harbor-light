import {createHash} from "node:crypto";
import {readdir,readFile,writeFile} from "node:fs/promises";
import {join,relative,sep} from "node:path";
import {fileURLToPath} from "node:url";

const appRoot=fileURLToPath(new URL("../app/demo/",import.meta.url));
const output=new URL("../lib/generated-inventory.ts",import.meta.url);
async function files(dir){const entries=await readdir(dir,{withFileTypes:true});const nested=await Promise.all(entries.map(entry=>entry.isDirectory()?files(join(dir,entry.name)):[join(dir,entry.name)]));return nested.flat()}
const routes=[];
for(const file of await files(appRoot)){
  if(!file.endsWith(`${sep}route.ts`))continue;
  const source=await readFile(file,"utf8");
  if(!source.includes('"text/html; charset=utf-8"'))continue;
  const folder=relative(appRoot,file).split(sep).slice(0,-1).join("/");
  routes.push(`/demo${folder?`/${folder}`:""}`);
}
routes.sort();
if(!routes.length||new Set(routes).size!==routes.length)throw new Error("release inventory must contain unique static HTML routes");
const inventory={schema:"harborlight.inventory.v1",generated_from:"next-release-route-scan",routes};
const canonical=value=>value===null||typeof value!=="object"?JSON.stringify(value):Array.isArray(value)?`[${value.map(canonical).join(",")}]`:`{${Object.keys(value).sort().map(key=>`${JSON.stringify(key)}:${canonical(value[key])}`).join(",")}}`;
const digest=createHash("sha256").update(canonical(inventory)).digest("hex");
await writeFile(output,`// Generated by scripts/generate-inventory.mjs; do not edit.\nexport const DEMO_INVENTORY=${JSON.stringify(inventory)} as const;\nexport const DEMO_INVENTORY_DIGEST=${JSON.stringify(digest)};\n`);
